// Embed the actual MIDI bytes so the catalog also works when opened with file://.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),folder=path.join(root,'dist/classical-midi');
const Midi=require('../dist/music-art-midi.js'),Core=require('../dist/music-art-core.js');
const manifest=JSON.parse(fs.readFileSync(path.join(folder,'manifest.json'),'utf8'));
const entries=manifest.pieces.map(piece=>{
  const bytes=fs.readFileSync(path.join(folder,piece.file)),parsed=Midi.parse(bytes,piece.title);
  if(piece.excerptSeconds){
    if(piece.excerptSeconds<=.8||piece.excerptSeconds>180||piece.excerptSeconds>=parsed.duration)throw new Error('Invalid excerpt: '+piece.id);
    const end=piece.excerptSeconds-.8;
    Core.normalize({...parsed,duration:piece.excerptSeconds,events:parsed.events.filter(n=>n.start<end).map(n=>({...n,duration:Math.min(n.duration,end-n.start)}))});
  }else Core.normalize(parsed);
  return {...piece,originalDuration:Math.round(parsed.duration*10000)/10000,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),base64:bytes.toString('base64')};
});
const code=`/* Generated by scripts/package_classical_midi.cjs. Sources and licenses: classical-midi/README.md. */
(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory(require('./music-art-midi.js'),require('./music-art-core.js'));else root.MusicArtClassics=factory(root.MusicArtMidi,root.MusicArtCore);})(typeof window==='object'?window:this,function(Midi,Core){
  'use strict';
  const entries=${JSON.stringify(entries)};
  function samples(){
    return entries.map(entry=>{
      const bytes=Uint8Array.from(atob(entry.base64),c=>c.charCodeAt(0));
      const parsed=Midi.parse(bytes,entry.title+' · '+entry.composer+(entry.excerptSeconds?'（节选）':''));
      if(entry.excerptSeconds){
        const end=entry.excerptSeconds-.8;
        parsed.events=parsed.events.filter(n=>n.start<end).map(n=>({...n,duration:Math.min(n.duration,end-n.start)}));
        parsed.duration=entry.excerptSeconds;
      }
      const {base64,...source}=entry;
      return {id:entry.id,...Core.normalize(parsed),source};
    });
  }
  return {samples};
});
`;
fs.writeFileSync(path.join(root,'dist/music-art-classics.js'),code);
console.log('Embedded '+entries.length+' classical MIDI files ('+Buffer.byteLength(code)+' bytes).');
